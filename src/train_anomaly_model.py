"""
train_anomaly_model.py
=======================
Trains an Edge-AI-ready Anomaly Detection model for the Industrial Heavy
Machinery (IHM) track, using the synthetic CWRU-bearing-style vibration
dataset generated by data/generate_data.py.

Approach:
    - Extract standard vibration health-monitoring features (RMS, kurtosis,
      crest factor, skewness, peak-to-peak, std).
    - Train an IsolationForest (unsupervised anomaly detector) on the
      'normal' operating segments only -- exactly how real condition
      monitoring systems are trained (they rarely have abundant labelled
      failure data, but plenty of normal operating data).
    - Evaluate against the held-out labelled data (early_fault / severe_fault
      treated as anomalies) to report precision/recall-style metrics.

Run:
    python src/train_anomaly_model.py
"""

import os
import sys
import joblib
import numpy as np
import pandas as pd
from sklearn.ensemble import IsolationForest
from sklearn.model_selection import train_test_split
from sklearn.metrics import classification_report, roc_auc_score
from sklearn.preprocessing import StandardScaler

sys.path.append(os.path.dirname(os.path.abspath(__file__)))
from utils import DATA_DIR, MODEL_DIR  # noqa: E402

FEATURE_COLS = ["rms", "std", "peak", "crest_factor", "kurtosis", "skewness", "peak_to_peak"]


def load_data():
    path = os.path.join(DATA_DIR, "ihm_bearing.csv")
    if not os.path.exists(path):
        raise FileNotFoundError(
            "IHM bearing dataset not found. Run `python data/generate_data.py` first."
        )
    return pd.read_csv(path)


def main():
    print("Loading IHM bearing (CWRU-style) dataset ...")
    df = load_data()

    # split machines into train/test so we evaluate on UNSEEN machines
    machine_ids = df["machine_id"].unique()
    train_ids, test_ids = train_test_split(machine_ids, test_size=0.3, random_state=42)

    train_df = df[df["machine_id"].isin(train_ids)]
    test_df = df[df["machine_id"].isin(test_ids)]

    # Train the anomaly detector ONLY on normal segments (realistic setup)
    normal_train = train_df[train_df["health_state"] == "normal"]

    scaler = StandardScaler()
    X_train_normal = scaler.fit_transform(normal_train[FEATURE_COLS])

    print("Training IsolationForest anomaly detector on normal operating data ...")
    model = IsolationForest(
        n_estimators=150,
        contamination=0.05,
        random_state=42,
        n_jobs=-1,
    )
    model.fit(X_train_normal)

    # Evaluate on held-out machines (mix of normal / early / severe fault)
    X_test = scaler.transform(test_df[FEATURE_COLS])
    y_test = test_df["is_anomaly"].values

    raw_scores = model.decision_function(X_test)  # higher = more normal
    anomaly_score = -raw_scores  # higher = more anomalous
    preds = (model.predict(X_test) == -1).astype(int)  # 1 = anomaly

    auc = roc_auc_score(y_test, anomaly_score)
    report = classification_report(y_test, preds, target_names=["normal", "anomaly"])

    print("\n--- Anomaly Detection Evaluation (held-out machines) ---")
    print(f"  ROC-AUC : {auc:.3f}")
    print(report)

    os.makedirs(MODEL_DIR, exist_ok=True)
    joblib.dump(
        {"model": model, "scaler": scaler, "feature_cols": FEATURE_COLS},
        os.path.join(MODEL_DIR, "anomaly_model.joblib"),
        compress=3,
    )
    print("Saved trained anomaly model -> models/anomaly_model.joblib")

    # Save test predictions for dashboard visualisation
    out_df = test_df[["machine_id", "timestep", "health_state", "is_anomaly"]].copy()
    out_df["anomaly_score"] = anomaly_score
    out_df["predicted_anomaly"] = preds
    out_df.to_csv(os.path.join(MODEL_DIR, "anomaly_test_predictions.csv"), index=False)
    print("Saved test predictions -> models/anomaly_test_predictions.csv")

    metrics = {"roc_auc": float(auc)}
    joblib.dump(metrics, os.path.join(MODEL_DIR, "anomaly_metrics.joblib"))


if __name__ == "__main__":
    main()
