"""
train_rul_model.py
==================
Trains an Edge-AI-ready Remaining Useful Life (RUL) prediction model for the
Aerospace track, using the synthetic CMAPSS-style dataset generated by
data/generate_data.py.

Pipeline:
    1. Load aerospace_train.csv / aerospace_test.csv
    2. Feature engineering (rolling mean/std over sensor readings)
    3. Train a RandomForestRegressor to predict RUL (Remaining Useful Life)
    4. Evaluate on held-out test units (RMSE, MAE, R2)
    5. Save the trained model + feature list to models/

Run:
    python src/train_rul_model.py
"""

import os
import sys
import joblib
import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

sys.path.append(os.path.dirname(os.path.abspath(__file__)))
from utils import add_rolling_features, DATA_DIR, MODEL_DIR  # noqa: E402


SENSOR_COLS = [f"sensor_{i}" for i in range(1, 9)]
FEATURE_COLS = None  # set after feature engineering


def load_data():
    train_path = os.path.join(DATA_DIR, "aerospace_train.csv")
    test_path = os.path.join(DATA_DIR, "aerospace_test.csv")
    if not (os.path.exists(train_path) and os.path.exists(test_path)):
        raise FileNotFoundError(
            "Aerospace dataset not found. Run `python data/generate_data.py` first."
        )
    return pd.read_csv(train_path), pd.read_csv(test_path)


def build_features(df):
    df = add_rolling_features(df, SENSOR_COLS, group_col="unit_id", window=5)
    feature_cols = (
        ["cycle", "op_setting_1", "op_setting_2", "op_setting_3"]
        + SENSOR_COLS
        + [f"{c}_roll_mean" for c in SENSOR_COLS]
        + [f"{c}_roll_std" for c in SENSOR_COLS]
    )
    return df, feature_cols


def main():
    print("Loading aerospace (CMAPSS-style) dataset ...")
    train_df, test_df = load_data()

    print("Engineering rolling-window features ...")
    train_df, feature_cols = build_features(train_df)
    test_df, _ = build_features(test_df)

    # Cap RUL at a reasonable ceiling (standard CMAPSS practice) so the
    # model isn't dominated by long, uninformative "healthy" stretches.
    RUL_CAP = 130
    train_df["RUL_capped"] = train_df["RUL"].clip(upper=RUL_CAP)
    test_df["RUL_capped"] = test_df["RUL"].clip(upper=RUL_CAP)

    X_train = train_df[feature_cols]
    y_train = train_df["RUL_capped"]
    X_test = test_df[feature_cols]
    y_test = test_df["RUL_capped"]

    print("Training RandomForestRegressor (RUL predictor) ...")
    model = RandomForestRegressor(
        n_estimators=150,
        max_depth=12,
        min_samples_leaf=3,
        n_jobs=-1,
        random_state=42,
    )
    model.fit(X_train, y_train)

    preds = model.predict(X_test)
    rmse = float(np.sqrt(mean_squared_error(y_test, preds)))
    mae = float(mean_absolute_error(y_test, preds))
    r2 = float(r2_score(y_test, preds))

    print("\n--- RUL Model Evaluation (held-out test engines) ---")
    print(f"  RMSE : {rmse:.2f} cycles")
    print(f"  MAE  : {mae:.2f} cycles")
    print(f"  R2   : {r2:.3f}")

    os.makedirs(MODEL_DIR, exist_ok=True)
    model_path = os.path.join(MODEL_DIR, "rul_model.joblib")
    joblib.dump(
        {"model": model, "feature_cols": feature_cols, "rul_cap": RUL_CAP},
        model_path,
        compress=3,
    )
    print(f"\nSaved trained RUL model -> {model_path}")

    # Save test predictions for dashboard visualisation
    out_df = test_df[["unit_id", "cycle", "RUL"]].copy()
    out_df["predicted_RUL"] = preds
    out_df.to_csv(os.path.join(MODEL_DIR, "rul_test_predictions.csv"), index=False)
    print("Saved test predictions -> models/rul_test_predictions.csv")

    metrics = {"rmse": rmse, "mae": mae, "r2": r2}
    joblib.dump(metrics, os.path.join(MODEL_DIR, "rul_metrics.joblib"))


if __name__ == "__main__":
    main()
